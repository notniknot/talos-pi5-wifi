#!/usr/bin/env python3
"""Build and package public release files locally. Does not publish or flash anything."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile

from build import ROOT, LOCK, validate_version


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--version', default=LOCK['default_version'])
    args = parser.parse_args()
    version = validate_version(args.version)
    output = ROOT / '_out/releases' / version
    if output.exists():
        parser.error(f'{output} exists; move it aside before building a new release')
    subprocess.run([sys.executable, str(ROOT / 'scripts/prepare.py')], check=True)
    subprocess.run([sys.executable, '-m', 'unittest', 'discover', '-s', 'tests', '-p', 'test_*.py'], cwd=ROOT, check=True)
    targets = ['kernel', 'wpa-supplicant', 'wireless-regdb', 'wifi-tests', 'boot-tests', 'image-tests', 'kernel-export', 'initramfs', 'installer', 'talosctl-linux-arm64', 'talosctl-darwin-arm64']
    for target in targets:
        subprocess.run([sys.executable, str(ROOT / 'scripts/build.py'), target, '--version', version], check=True)
    boot = ROOT / '_out/boot'
    if boot.exists():
        # This directory is exclusively generated by assemble-boot.py.
        shutil.rmtree(boot)
    subprocess.run([sys.executable, str(ROOT / 'scripts/assemble-boot.py')], check=True)
    output.mkdir(parents=True)
    with tarfile.open(output / f'talos-pi5-wifi-{version}-arm64-boot.tar.gz', 'w:gz') as archive:
        archive.add(boot, arcname='.')
    for source, name in [
        ('installer/installer-arm64.oci.tar', f'talos-pi5-wifi-{version}-arm64-installer.oci.tar'),
        ('talosctl-linux-arm64/talosctl-linux-arm64', 'talosctl-linux-arm64'),
        ('talosctl-darwin-arm64/talosctl-darwin-arm64', 'talosctl-darwin-arm64'),
        ('kernel-export/kernel.spdx.json', 'kernel.spdx.json'),
    ]:
        shutil.copyfile(ROOT / '_out' / source, output / name)
    revision = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    dirty = bool(subprocess.check_output(['git', 'status', '--porcelain'], cwd=ROOT))
    metadata = dict(version=version, upstream_version=LOCK['upstream_version'], project_commit=revision, project_dirty=dirty, hardware_validated=False, sources=LOCK)
    (output / 'build.json').write_text(json.dumps(metadata, indent=2) + '\n')
    # An allowlist above, not a recursive copy of _out: private images stay local.
    checksums = []
    for path in sorted(output.iterdir()):
        with path.open('rb') as stream:
            checksums.append(f'{hashlib.file_digest(stream, "sha256").hexdigest()}  {path.name}\n')
    (output / 'SHA256SUMS').write_text(''.join(checksums))
    print(f'Public artifacts: {output}\nHardware validation and disk integration testing are still required before publication.')


if __name__ == '__main__':
    main()
